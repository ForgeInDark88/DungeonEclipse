def tres(i, note):
    nid, biome, boss, title, author, text = note
    esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
    return ('[gd_resource type="Resource" script_class="LoreData" load_steps=2 format=3]\n\n'
            '[ext_resource type="Script" path="res://scripts/data/lore_data.gd" id="1_lore"]\n\n'
            '[resource]\nscript = ExtResource("1_lore")\nid = &"%s"\ntitle = "%s"\nauthor = "%s"\n'
            'text = "%s"\nbiome = &"%s"\nboss = &"%s"\norder = %d\n') % (
        nid, esc(title), esc(author), esc(text), biome, boss, i)


