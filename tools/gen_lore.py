def lectern():
    """16x24: a stone lectern with an open journal, a faint glow on the pages."""
    im = blank(16, 24)
    g = blank(16, 24)
    stone = (110, 104, 116)
    m = mask(16, 24, lambda d: d.polygon([(6, 11), (10, 11), (11, 21), (5, 21)], fill=FULL))
    lit(im, m, stone, 7, 13, 3, 6)
    d = ImageDraw.Draw(im)
    d.rectangle((3, 21, 13, 23), fill=rgba(sh(stone, 0.8)))
    d.line((3, 21, 13, 21), fill=rgba(sh(stone, 1.2)))
    # slanted top
    d.polygon([(1, 10), (15, 7), (15, 10), (1, 13)], fill=rgba(sh(stone, 0.9)))
    # the open journal: two pages, a spine, lines of writing
    d.polygon([(2, 9), (8, 7), (8, 10), (2, 12)], fill=rgba((236, 222, 186)))
    d.polygon([(8, 7), (14, 5), (14, 8), (8, 10)], fill=rgba((222, 206, 168)))
    d.line((8, 7, 8, 10), fill=rgba((120, 70, 40)))
    for k in range(2):
        d.line((3, 10 - k, 7, 9 - k - 1), fill=rgba((110, 90, 70)))
        d.line((9, 8 - k, 13, 7 - k - 1), fill=rgba((110, 90, 70)))
    d.line((14, 5, 15, 3), fill=rgba((200, 40, 40)))  # ribbon bookmark
    glow_dot(g, 8, 8, 5.0, (255, 230, 160), 0.55)
    return finish(im, g)


def bottle():
    """16x16: a message in a bottle half sunk in silt (Drowned Vaults)."""
    im = blank(16, 16)
    g = blank(16, 16)
    glass = (110, 190, 170)
    m = mask(16, 16, lambda d: d.rounded_rectangle((2, 8, 12, 14), 3, fill=FULL))
    lit(im, m, glass, 5, 9, 5, 3, alpha=220)
    d = ImageDraw.Draw(im)
    d.rectangle((12, 10, 14, 12), fill=rgba(sh(glass, 0.9), 220))  # neck
    d.rectangle((14, 10, 15, 12), fill=rgba((150, 110, 70)))  # cork
    d.rectangle((4, 10, 10, 12), fill=rgba((236, 222, 186)))  # rolled note inside
    d.line((5, 11, 9, 11), fill=rgba((180, 60, 50)))  # string
    d.point((4, 9), fill=rgba((230, 255, 250)))
    d.line((0, 15, 15, 15), fill=rgba((70, 90, 84)))
    glow_dot(g, 7, 11, 4.0, (200, 255, 230), 0.45)
    return finish(im, g)


def main():
    os.makedirs(DATA, exist_ok=True)
    for f in os.listdir(DATA):
        if f.endswith(".tres"):
            os.remove(os.path.join(DATA, f))
    for i, note in enumerate(NOTES):
        with open(os.path.join(DATA, note[0] + ".tres"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(tres(i, note))
    world = os.path.join(gp.A, "sprites", "props")
    os.makedirs(world, exist_ok=True)
    lectern().save(os.path.join(world, "lore_note.png"))
    bottle().save(os.path.join(world, "lore_bottle.png"))
    print("lore: %d notes" % len(NOTES))


if __name__ == "__main__":
    main()
