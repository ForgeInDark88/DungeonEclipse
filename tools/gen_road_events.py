def main() -> None:
    out_dir = os.path.join(ROOT, "data", "road_events")
    os.makedirs(out_dir, exist_ok=True)
    for (eid, title, regions, dmin, dmax, weight, text, options) in EVENTS:
        regs = ", ".join('&"%s"' % x for x in regions)
        opts = "Array[Dictionary]([" + ", ".join(gd_value(x) for x in options) + "])"
        with open(os.path.join(out_dir, eid + ".tres"), "w", encoding="utf-8") as f:
            f.write(f'''[gd_resource type="Resource" script_class="EventData" load_steps=2 format=3]

[ext_resource type="Script" path="res://scripts/data/event_data.gd" id="1"]

[resource]
script = ExtResource("1")
id = &"{eid}"
title = {q(title)}
text = {q(text)}
regions = Array[StringName]([{regs}])
min_depth = {dmin}
max_depth = {dmax}
weight = {weight}
prop = &"{PROPS.get(eid, 'shrine')}"
options = {opts}
''')
    print("events: %d" % len(EVENTS))


if __name__ == "__main__":
    main()
